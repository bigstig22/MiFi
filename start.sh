# Function to setup TAK configuration
setup_tak_config() {
    print_status "TAK Server Configuration (optional)..."
    
    if [ ! -f "config/config.ini" ]; then
        print_warning "config/config.ini not found, skipping TAK configuration"
        return 0
    fi
    
    while true; do
        read -p "Do you want to configure TAK Server integration? (y/n): " configure_tak
        if [[ "$configure_tak" == "y" ]] || [[ "$configure_tak" == "Y" ]]; then
            break
        elif [[ "$configure_tak" == "n" ]] || [[ "$configure_tak" == "N" ]]; then
            print_info "Skipping TAK configuration"
            return 0
        else
            print_warning "Please enter exactly 'y' or 'n'"
        fi
    done
    
    # Read current config
    TAK_ENABLED=$(grep -E "^enabled\s*=" config/config.ini | grep -i "\[TAK\]" -A 10 | grep "^enabled" | cut -d'=' -f2 | tr -d ' ' || echo "false")
    
    # Enable TAK
    print_info "Enabling TAK integration..."
    sed -i '/^\[TAK\]/,/^\[/ s/^enabled = .*/enabled = true/' config/config.ini || \
    sed -i '/^\[TAK\]/a enabled = true' config/config.ini
    
    # Get TAK host
    read -p "Enter TAK Server hostname or IP address: " tak_host
    if [ -n "$tak_host" ]; then
        sed -i '/^\[TAK\]/,/^\[/ s/^host = .*/host = '"$tak_host"'/' config/config.ini || \
        sed -i '/^\[TAK\]/a host = '"$tak_host"'' config/config.ini
    fi
    
    # Get TAK port
    read -p "Enter TAK Server Streaming port [8087]: " tak_port
    tak_port=${tak_port:-8087}
    sed -i '/^\[TAK\]/,/^\[/ s/^port = .*/port = '"$tak_port"'/' config/config.ini || \
    sed -i '/^\[TAK\]/a port = '"$tak_port"'' config/config.ini
    
    # Get protocol
    read -p "Enter protocol (tcp/udp) [tcp]: " tak_protocol
    tak_protocol=${tak_protocol:-tcp}
    sed -i '/^\[TAK\]/,/^\[/ s/^protocol = .*/protocol = '"$tak_protocol"'/' config/config.ini || \
    sed -i '/^\[TAK\]/a protocol = '"$tak_protocol"'' config/config.ini
    
    # Ask about authentication
    print_info "Certificate files should be placed in the 'tak' folder"
    read -p "Use certificate authentication? (y/n) [n]: " use_certs
    if [[ "$use_certs" =~ ^[Yy]$ ]]; then
        echo ""
        print_info "PKCS#12 Certificate File (.p12) - REQUIRED"
        print_info "  This file contains both your client certificate and private key"
        print_info "  File extension must be .p12 or .pfx"
        print_info "  Example: MiFi-Scanner.p12, lab-field.p12"
        while true; do
            read -p "Enter .p12 certificate filename (will be placed in 'tak' folder) or full path: " cert_file
            if [ -z "$cert_file" ]; then
                print_warning "Certificate file is required. Please enter a filename."
                continue
            fi
            # Validate it's a .p12 or .pfx file
            if [[ ! "$cert_file" =~ \.(p12|pfx)$ ]]; then
                print_warning "Certificate file must have .p12 or .pfx extension"
                read -p "Continue anyway? (y/n): " continue_anyway
                if [[ "$continue_anyway" =~ ^[Yy]$ ]]; then
                    break
                fi
            else
                break
            fi
        done
        
        if [ -n "$cert_file" ]; then
            # If it's not an absolute path, assume it's a filename for the tak folder
            if [[ "$cert_file" != /* ]]; then
                cert_path="tak/$cert_file"
                print_info "Certificate will be expected at: $cert_path"
            else
                cert_path="$cert_file"
            fi
            sed -i '/^\[TAK\]/,/^\[/ s|^cert_file = .*|cert_file = '"$cert_file"'|' config/config.ini || \
            sed -i '/^\[TAK\]/a cert_file = '"$cert_file"'' config/config.ini
        fi
        
        echo ""
        print_info "CA Certificate File (.pem) - RECOMMENDED"
        print_info "  Used to verify the TAK server's certificate for secure connections"
        print_info "  File extension should be .pem, .crt, or .cer"
        print_info "  Example: ca.pem, root.pem"
        print_info "  Note: This is optional but recommended for production use"
        read -p "Enter CA certificate filename (optional, will be placed in 'tak' folder) or full path (press Enter to skip): " ca_file
        if [ -n "$ca_file" ]; then
            if [[ "$ca_file" != /* ]]; then
                ca_path="tak/$ca_file"
                print_info "CA certificate will be expected at: $ca_path"
            else
                ca_path="$ca_file"
            fi
            sed -i '/^\[TAK\]/,/^\[/ s|^ca_file = .*|ca_file = '"$ca_file"'|' config/config.ini || \
            sed -i '/^\[TAK\]/a ca_file = '"$ca_file"'' config/config.ini
        else
            print_info "Skipping CA certificate (server verification will be disabled)"
        fi
    else
        read -p "Use API token authentication? (y/n) [n]: " use_token
        if [[ "$use_token" =~ ^[Yy]$ ]]; then
            read -p "Enter API token: " api_token
            if [ -n "$api_token" ]; then
                sed -i '/^\[TAK\]/,/^\[/ s|^api_token = .*|api_token = '"$api_token"'|' config/config.ini || \
                sed -i '/^\[TAK\]/a api_token = '"$api_token"'' config/config.ini
            fi
        fi
    fi
    
    print_status "TAK configuration saved to config/config.ini"
    print_info "You can edit config/config.ini manually to change TAK settings later"
}

# Function to check WiFi interface
check_wifi_interface() {
    print_status "Checking for WiFi interfaces..."
    
    if command_exists iw; then
        INTERFACES=$(iw dev 2>/dev/null | grep -E "Interface" | awk '{print $2}')
        if [ -z "$INTERFACES" ]; then
            print_warning "No wireless interfaces detected"
            print_info "Make sure your WiFi adapter is connected and drivers are installed"
        else
            print_info "Detected wireless interfaces:"
            for iface in $INTERFACES; do
                echo "  - $iface"
            done
        fi
    else
        print_warning "iw command not found, cannot check interfaces"
    fi
}

# Function to verify installation
verify_installation() {
    print_status "Verifying installation..."
    
    VERIFY_ERRORS=0
    
    # Check Python packages
    print_info "Checking Python packages..."
    python3 -c "import tabulate, serial, gps3, flask" 2>/dev/null || {
        print_error "Some Python packages are missing"
        ((VERIFY_ERRORS++))
    }
    
    # Check system commands
    print_info "Checking system commands..."
    COMMANDS=("aircrack-ng" "airodump-ng" "aireplay-ng" "john" "hashcat")
    for cmd in "${COMMANDS[@]}"; do
        if ! command_exists "$cmd"; then
            print_error "$cmd not found in PATH"
            ((VERIFY_ERRORS++))
        fi
    done
    
    # Check for wpapcap2john (from John the Ripper Jumbo)
    print_info "Checking wpapcap2john..."
    if ! command_exists wpapcap2john; then
        print_error "wpapcap2john not found in PATH (required for WPA handshake analysis)"
        print_info "This tool is part of John the Ripper Jumbo"
        print_info "Run './start.sh' again to install it, or install manually"
        ((VERIFY_ERRORS++))
    else
        print_info "wpapcap2john is available"
    fi
    
    # Check directories
    print_info "Checking directories..."
    DIRS=("logs" "collection" "config")
    for dir in "${DIRS[@]}"; do
        if [ ! -d "$dir" ]; then
            print_error "Directory missing: $dir"
            ((VERIFY_ERRORS++))
        fi
    done
    
    # Check database file
    if [ ! -f "config/networks.db" ]; then
        print_error "Database file missing: config/networks.db"
        ((VERIFY_ERRORS++))
    fi
    
    if [ $VERIFY_ERRORS -eq 0 ]; then
        print_status "Installation verification passed!"
        return 0
    else
        print_error "Installation verification failed with $VERIFY_ERRORS errors"
        return 1
    fi
}

